import React from 'react';
import { AbsoluteFill, useCurrentFrame, interpolate } from 'remotion';
import { LogoFooter } from '../Logo';
import { colors, typography, layout } from '../tokens';
import { FadeText } from '../animations/FadeText';

type Props = {
  label?: string;
  title?: string;
  titleHighlight?: string;
  // Scene-relative frame the AI document card fades in. Default 0.
  cardAppearFrame?: number;
  // Scene-relative frame "CONFIDENT" + its lime rule appear.
  confidentAppearFrame?: number;
  // Scene-relative frame the "≠" and "CORRECT" pay-off appears.
  notEqualAppearFrame?: number;
};

const GREY = '#444444';
const LIME = '#85E13A';

// AI document card (confident, polished report) vs. a plain "CONFIDENT ≠ CORRECT"
// statement — illustrates that a fluent, well-formatted answer isn't proof it's right.
export const DoubtConfidenceDiagram: React.FC<Props> = ({
  label = 'LETTER 1 OF 5',
  title = 'D Is for Doubt',
  titleHighlight = 'D',
  cardAppearFrame = 0,
  confidentAppearFrame = 20,
  notEqualAppearFrame = 268,
}) => {
  const frame = useCurrentFrame();

  const cardOpacity = interpolate(frame - cardAppearFrame, [0, 20], [0, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });
  const cardY = interpolate(frame - cardAppearFrame, [0, 20], [16, 0], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });

  const confidentOpacity = interpolate(frame - confidentAppearFrame, [0, 20], [0, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });
  const ruleScale = interpolate(frame - confidentAppearFrame - 20, [0, 20], [0, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });

  const notEqualOpacity = interpolate(frame - notEqualAppearFrame, [0, 18], [0, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });
  const correctOpacity = interpolate(frame - notEqualAppearFrame - 20, [0, 18], [0, 1], {
    extrapolateLeft: 'clamp',
    extrapolateRight: 'clamp',
  });

  const DIAGRAM_WIDTH = 1120;
  const DIAGRAM_HEIGHT = 640;

  return (
    <AbsoluteFill style={{ backgroundColor: colors.white }}>
      {/* Label + title, top-left safe margin */}
      <div style={{ position: 'absolute', left: layout.safeMargin, top: layout.safeMargin }}>
        {label ? <div style={{ ...typography.label, marginBottom: 32 }}>{label}</div> : null}
        {title ? (
          <div style={{ ...typography.title, color: colors.black }}>
            <FadeText text={title} highlight={titleHighlight} />
          </div>
        ) : null}
      </div>

      {/* Diagram, centered below the title */}
      <div
        style={{
          position: 'absolute',
          left: (layout.width - DIAGRAM_WIDTH) / 2,
          top: 320,
          width: DIAGRAM_WIDTH,
          height: DIAGRAM_HEIGHT,
        }}
      >
        <svg width={DIAGRAM_WIDTH} height={DIAGRAM_HEIGHT} viewBox="0 0 1400 800" xmlns="http://www.w3.org/2000/svg">
          {/* ── LEFT: AI document card ── */}
          <g style={{ opacity: cardOpacity }} transform={`translate(0, ${cardY})`}>
            <rect x={115} y={125} width={520} height={590} rx={20} fill="#FFFFFF" stroke={LIME} strokeWidth={3} transform="rotate(-3 115 125)" />
            <rect x={140} y={100} width={540} height={600} rx={20} fill="#FFFFFF" stroke={GREY} strokeWidth={4} />

            <rect x={180} y={145} width={64} height={64} rx={10} fill={LIME} />
            <text x={212} y={188} textAnchor="middle" fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={28} fontWeight={700}>
              AI
            </text>

            <text x={275} y={175} fill={GREY} fontFamily="'IBM Plex Serif', Georgia, serif" fontSize={38}>
              Market Analysis
            </text>
            <text x={275} y={205} fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={16} letterSpacing={2}>
              GENERATED BY AI
            </text>

            <line x1={180} y1={230} x2={640} y2={230} stroke={GREY} strokeWidth={2} />

            <text x={180} y={275} fill={GREY} fontFamily="'IBM Plex Serif', Georgia, serif" fontSize={28}>
              Key Findings
            </text>

            <circle cx={205} cy={320} r={18} fill={LIME} />
            <path d="M196 320 L203 327 L216 313" stroke="#FFFFFF" strokeWidth={4} strokeLinecap="round" strokeLinejoin="round" fill="none" />
            <text x={240} y={328} fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={20}>
              Strong revenue growth expected
            </text>

            <circle cx={205} cy={365} r={18} fill={LIME} />
            <path d="M196 365 L203 372 L216 358" stroke="#FFFFFF" strokeWidth={4} strokeLinecap="round" strokeLinejoin="round" fill="none" />
            <text x={240} y={373} fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={20}>
              Expanding market opportunity
            </text>

            <circle cx={205} cy={410} r={18} fill={LIME} />
            <path d="M196 410 L203 417 L216 403" stroke="#FFFFFF" strokeWidth={4} strokeLinecap="round" strokeLinejoin="round" fill="none" />
            <text x={240} y={418} fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={20}>
              Favorable competitive position
            </text>

            <text x={180} y={470} fill={GREY} fontFamily="'IBM Plex Serif', Georgia, serif" fontSize={26}>
              Projected Growth
            </text>

            <line x1={190} y1={610} x2={620} y2={610} stroke={GREY} strokeWidth={2} />

            <rect x={225} y={565} width={55} height={45} fill={LIME} />
            <rect x={305} y={535} width={55} height={75} fill={LIME} />
            <rect x={385} y={505} width={55} height={105} fill={LIME} />
            <rect x={465} y={470} width={55} height={140} fill={LIME} />
            <rect x={545} y={435} width={55} height={175} fill={LIME} />

            <text x={252} y={640} textAnchor="middle" fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={14}>1</text>
            <text x={332} y={640} textAnchor="middle" fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={14}>2</text>
            <text x={412} y={640} textAnchor="middle" fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={14}>3</text>
            <text x={492} y={640} textAnchor="middle" fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={14}>4</text>
            <text x={572} y={640} textAnchor="middle" fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={14}>5</text>
          </g>

          {/* ── RIGHT: CONFIDENT ≠ CORRECT ── */}
          <g style={{ opacity: confidentOpacity }}>
            <text x={1035} y={285} textAnchor="middle" fill={GREY} fontFamily="'IBM Plex Serif', Georgia, serif" fontSize={64}>
              CONFIDENT
            </text>
            <rect x={820} y={315} width={430 * ruleScale} height={12} rx={6} fill={LIME} />
          </g>

          <text x={1035} y={450} textAnchor="middle" fill={GREY} fontFamily="'Public Sans', Arial, sans-serif" fontSize={96} fontWeight={700} style={{ opacity: notEqualOpacity }}>
            ≠
          </text>

          <text x={1035} y={575} textAnchor="middle" fill={GREY} fontFamily="'IBM Plex Serif', Georgia, serif" fontSize={64} style={{ opacity: correctOpacity }}>
            CORRECT
          </text>
        </svg>
      </div>

      <LogoFooter variant="dark" />
    </AbsoluteFill>
  );
};
